def _f(v: Any) -> Any:
    """Plain float (or None) for table cells; NaN becomes None."""
    if v is None:
        return None
    if isinstance(v, (bool, np.bool_)):
        return bool(v)
    try:
        x = float(v)
    except (TypeError, ValueError):
        return v
    return None if math.isnan(x) else x


def equivalent_to(method_id: str) -> Optional[str]:
    """``pair_id`` values of :func:`ration_reliability.optimization.equivalence_annotations`
    (``METHOD_EQUIVALENCES``, acceptance D06) that involve ``method_id``, joined by ``;``;
    ``None`` (empty cell) when the method has no registered equivalence.

    Method-level annotation: the pair's ``condition`` (e.g. ``alpha_train=0`` for
    ``EQ-M3c-M2-ALPHA0``, ``margin_scale='sd'`` for ``EQ-M1-M3a``) is not evaluated here; read it in
    ``METHOD_EQUIVALENCES`` before merging two rows."""
    ids = [str(rec["pair_id"]) for rec in equivalence_annotations(method_id)]
    return ";".join(ids) if ids else None


def long_table(runs: Sequence[MethodRun], *, run_id: str, meta: Mapping[str, Any],
               confidence: float = 0.95) -> list[dict[str, Any]]:
    """Result long table (T9 minimum fields).  One ``joint`` row per method plus one row per
    evaluated constraint.  Methods without a ration keep a single ``joint`` row with empty cost
    and risk fields (the denominator is never shrunk).  ``equivalent_to`` lists the equivalence
    pair ids of the method (:func:`equivalent_to`, D06); it does not change any number."""
    rows: list[dict[str, Any]] = []
    for r in runs:
        res = r.result
        sel = r.selection
        base: dict[str, Any] = {c: None for c in LONG_COLUMNS}
        base.update({
            "run_id": run_id,
            "run_type": meta.get("run_type"),
            "scenario_id": meta.get("scenario_id"),
            "animal_profile_id": meta.get("animal_profile_id"),
            "inventory_id": meta.get("inventory_id"),
            "price_id": meta.get("price_id"),
            "method_id": r.spec.method_id,
            "method_label": r.spec.name,
            "equivalent_to": equivalent_to(r.spec.method_id),
            "target_alpha": meta.get("target_alpha"),
            "solver_status": None if res is None else str(res.status),
            "selection_status": "not_applicable" if sel is None else sel.status,
            "selected_param": (None if sel is None or sel.status != "selected"
                               else f"{sel.param_name}={sel.selected_value}"),
            "feasibility_status": r.status,
            "cost": None if r.evaluation is None else _f(r.evaluation.cost),
            "cost_unit": meta.get("cost_unit"),
            "mip_gap": None if res is None else _f(res.mip_gap),
            "solve_wall_time_s": None if res is None else _f(res.wall_time_s),
            "independent_empirical_n": meta.get("independent_empirical_n"),
            "is_synthetic": bool(meta.get("is_synthetic")) or bool(res is not None and res.is_synthetic),
            "provenance_id": meta.get("provenance_id"),
            "test_stream_id": meta.get("test_stream_id"),
        })
        if r.evaluation is None:
            row = dict(base)
            row.update({"row_type": "joint", "constraint_id": "JOINT_I",
                        "constraint_class": "probabilistic_nutrition(joint)"})
            rows.append(row)
            continue
        s = r.evaluation.summary(confidence)
        j = s["joint"]
        row = dict(base)
        cp = j.get("mc_clopper_pearson") or {}
        row.update({
            "row_type": "joint", "constraint_id": "JOINT_I", "constraint_class": "probabilistic_nutrition(joint)",
            "mc_draw_count": j["n_draws"], "n_defined": j["n_draws"] - j["n_unknown"],
            "n_violated": j["n_violated"], "n_unknown": j["n_unknown"],
            "rate_lower": _f(j["rate_lower"]), "rate_upper": _f(j["rate_upper"]),
            "rate_among_evaluable": _f(j["rate_among_evaluable"]),
            "ci_type": cp.get("interval_type"), "ci_confidence": _f(cp.get("confidence")),
            "ci_lower": _f(cp.get("lower")), "ci_upper": _f(cp.get("upper")),
            "structural_ok": bool(s["structural_ok"]), "n_data_quality_flagged": s["n_data_quality_flagged"],
        })
        rows.append(row)
        for cid, pc in s["per_constraint"].items():
            row = dict(base)
            nd, nv = pc["n_defined"], pc["n_violated"]
            lo, hi = clopper_pearson(nv, nd, confidence) if nd else (None, None)
            mq = pc["margin_quantiles"] or {}
            row.update({
                "row_type": "constraint", "constraint_id": cid, "constraint_class": pc["class"], "unit": pc["unit"],
                "tolerance": _f(pc["tolerance"]), "mc_draw_count": s["n_draws"], "n_defined": nd,
                "n_violated": nv, "n_unknown": pc["n_undefined"],
                "rate_lower": _f(nv / s["n_draws"]) if s["n_draws"] else None,
                "rate_upper": _f((nv + pc["n_undefined"]) / s["n_draws"]) if s["n_draws"] else None,
                "rate_among_evaluable": _f(pc["violation_rate_among_defined"]),
                "ci_type": CI_TYPE if nd else None, "ci_confidence": confidence if nd else None,
                "ci_lower": _f(lo), "ci_upper": _f(hi),
                "mean_deficit_given_violation": _f(pc["mean_deficit_given_violation"]),
                "max_deficit": _f(pc["max_deficit"]),
                "margin_q01": _f(mq.get(0.01)), "margin_q05": _f(mq.get(0.05)), "margin_q50": _f(mq.get(0.5)),
                "structural_ok": bool(s["structural_ok"]),
            })
            rows.append(row)
    return rows


def ration_table(runs: Sequence[MethodRun], problem: RationProblem, *, run_id: str) -> list[dict[str, Any]]:
    """Executed ration ``q`` (kg as-fed/head/d) and planned DM share ``q d_hat / sum(q d_hat)``.

    Methods without a ration get one row with empty values (kept, not dropped)."""
    rows: list[dict[str, Any]] = []
    for r in runs:
        if not r.has_ration:
            rows.append({"run_id": run_id, "method_id": r.spec.method_id, "method_label": r.spec.name,
                         "solver_status": r.status, "ingredient_id": None, "q_as_fed_kg_per_head_d": None,
                         "planned_dm_share": None, "is_synthetic": problem.is_synthetic})
            continue
        dec = r.result.decision
        if dec.ingredient_ids != problem.ingredient_ids:
            raise ValueError(f"{r.spec.name}: decision ingredient order differs from the problem")
        x = np.asarray(dec.x_planned_dm, float)
        tot = float(x.sum())
        for i, iid in enumerate(dec.ingredient_ids):
            rows.append({"run_id": run_id, "method_id": r.spec.method_id, "method_label": r.spec.name,
                         "solver_status": r.status, "ingredient_id": iid,
                         "q_as_fed_kg_per_head_d": float(dec.q_as_fed[i]),
                         "planned_dm_share": (float(x[i] / tot) if tot > 0 else None),
                         "is_synthetic": bool(problem.is_synthetic or r.result.is_synthetic)})
    return rows


def _unit_scale(dimension: str) -> tuple[float, str]:
    return (100.0, "%DM") if dimension == "mass_fraction" else (1.0, "Mcal/kg DM")


def nutrient_profile(runs: Sequence[MethodRun], problem: RationProblem, draws: DrawSet, *, run_id: str,
                     group: str = "forage", group_nutrient: str = "NDF",
                     quantiles: Sequence[float] = (0.05, 0.5, 0.95)) -> list[dict[str, Any]]:
    """Descriptive ration profile for plausibility checks (not a risk metric).

    ``planned_nominal``: at the nominal composition and ``d_hat`` (what the formulator planned).
    ``draw_*``: quantiles of the *realised* values on ``draws`` (``x_real = q d``, never renormalised):
    supplied DM ``D`` (kg/d), each nutrient concentration ``N_j / D``, the group-weighted
    concentration (e.g. forage NDF) and the planned group DM share.  Undefined draws (missing data
    of a used ingredient) are counted and excluded from the quantiles.
    """
    ids = problem.ingredient_ids
    if draws.ingredient_ids != ids or draws.nutrient_ids != problem.nutrient_ids:
        raise ValueError("nutrient_profile: draw labels differ from the problem")
    w = np.array([float(g.group_weights.get(group, 0.0)) for g in problem.ingredients])
    theta0 = problem.nominal_theta()
    jn = problem.nutrient_ids.index(group_nutrient) if group_nutrient in problem.nutrient_ids else None
    rows: list[dict[str, Any]] = []
    for r in runs:
        if not r.has_ration:
            continue
        dec = r.result.decision
        q, dh = np.asarray(dec.q_as_fed, float), np.asarray(dec.d_hat, float)
        used = q != 0
        x0 = q * dh
        D0 = float(x0.sum())
        xr = np.where(used[None, :], draws.d * q[None, :], 0.0)             # [S, I], not renormalised
        th = np.where(used[None, :, None], draws.theta, 0.0)
        miss = (np.isnan(draws.d) & used[None, :]).any(axis=1) | \
            (np.isnan(draws.theta) & used[None, :, None]).any(axis=(1, 2))
        D = xr.sum(axis=1)
        items: list[tuple[str, str, float, np.ndarray]] = [("DM_supply", "kg DM/head/d", D0, D)]
        for j, n in enumerate(problem.nutrients):
            sc, unit = _unit_scale(n.dimension)
            nom = float(np.sum(x0 * np.where(used, theta0[:, j], 0.0)) / D0) * sc if D0 > 0 else float("nan")
            with np.errstate(invalid="ignore", divide="ignore"):
                val = (xr * th[:, :, j]).sum(axis=1) / D * sc
            items.append((f"{n.nutrient_id}_conc", unit, nom, val))
        if jn is not None and np.any(w > 0):
            sc, unit = _unit_scale(problem.nutrients[jn].dimension)
            nom = float(np.sum(x0 * w * np.where(used, theta0[:, jn], 0.0)) / D0) * sc if D0 > 0 else float("nan")
            with np.errstate(invalid="ignore", divide="ignore"):
                val = (xr * w[None, :] * th[:, :, jn]).sum(axis=1) / D * sc
            items.append((f"G:{group}:{group_nutrient}_conc", unit, nom, val))
        if np.any(w > 0):
            items.append((f"planned_{group}_dm_share", "fraction of planned DM",
                          float((x0 * w).sum() / D0) if D0 > 0 else float("nan"), None))
        for name, unit, nom, val in items:
            row = {"run_id": run_id, "method_id": r.spec.method_id, "method_label": r.spec.name, "quantity": name,
                   "unit": unit, "planned_nominal": _f(nom), "draw_p05": None, "draw_p50": None, "draw_p95": None,
                   "n_draws": None, "n_undefined": None, "draws_stream_id": None,
                   "is_synthetic": bool(problem.is_synthetic or draws.is_synthetic)}
            if val is not None:
                ok = ~miss & np.isfinite(val)
                qs = np.quantile(val[ok], list(quantiles)) if ok.any() else [None] * len(quantiles)
                row.update({"draw_p05": _f(qs[0]), "draw_p50": _f(qs[1]), "draw_p95": _f(qs[2]),
                            "n_draws": int(draws.n_draws), "n_undefined": int((~ok).sum()),
                            "draws_stream_id": draws.stream_id})
            rows.append(row)
    return rows


def write_csv(rows: Iterable[Mapping[str, Any]], path: str | Path, columns: Sequence[str]) -> Path:
    """Write rows with a fixed header; ``None`` is written as an empty cell (never as 0).

    Refuses to overwrite an existing file (result files are append-only, like run records)."""
    p = Path(path)
    if p.exists():
        raise FileExistsError(f"{p} already exists")
    p.parent.mkdir(parents=True, exist_ok=True)
    with open(p, "x", encoding="utf-8", newline="") as fh:
        wr = csv.DictWriter(fh, fieldnames=list(columns), extrasaction="raise")
        wr.writeheader()
        for row in rows:
            wr.writerow({c: ("" if row.get(c) is None else row.get(c)) for c in columns})
    return p


def probabilistic_ids(problem: RationProblem) -> tuple[str, ...]:
    """Ids of the ``probabilistic_nutrition`` constraints (members of the joint event I)."""
    cc = problem.compiled
    return tuple(cc.constraint_ids[k] for k in cc.indices(ConstraintClass.PROBABILISTIC_NUTRITION))
