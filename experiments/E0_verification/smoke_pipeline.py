@dataclass(frozen=True)
class MethodSpec:
    """One method call.

    ``params`` go to the registered solve function.  ``selection`` (optional) is a mapping with
    ``param_name``, ``grid``, ``target_alpha``, ``screening_rule`` and optionally ``confidence``;
    the parameter is then chosen on ``validation`` draws.  ``uses_opt_draws=False`` for methods
    that must not receive draws (e.g. M0 ``nominal_point``).
    """

    method_id: str
    params: Mapping[str, Any] = field(default_factory=dict)
    selection: Optional[Mapping[str, Any]] = None
    label: Optional[str] = None
    uses_opt_draws: bool = True

    @property
    def name(self) -> str:
        return self.label or self.method_id


@dataclass
class MethodRun:
    """Outcome of one :class:`MethodSpec`.  ``result`` is ``None`` only for selection ``not_met``."""

    spec: MethodSpec
    result: Optional[SolveResult]
    selection: Optional[ValidationSelection] = None
    evaluation: Optional[EvaluationResult] = None
    #: model fingerprint of the ``opt`` draws given to :func:`run_methods` (the declared world).
    world_fingerprint: Optional[str] = None
    #: set only when the test draws come from a declared, named different world (e.g. E2 shift).
    world_shift_scenario: Optional[str] = None

    @property
    def has_ration(self) -> bool:
        return self.result is not None and self.result.has_solution

    @property
    def status(self) -> str:
        """``optimal`` / ``feasible_time_limit`` / failure status / ``selection_not_met``."""
        if self.selection is not None and self.selection.status != "selected":
            return f"selection_{self.selection.status}"
        assert self.result is not None
        return str(self.result.status)


def build_world(spec_or_model, streams: RandomStreams, *, n_opt: Optional[int] = None,
                n_validation: Optional[int] = None, n_test: Optional[int] = None,
                model_id: Optional[str] = None) -> tuple[FactoryModel, dict[str, DrawSet]]:
    """Build (or take) the uncertainty-factory model and draw every requested purpose stream from it.

    ``spec_or_model`` is an :class:`UncertaintySpec` (built with
    :func:`~ration_reliability.uncertainty.factory.build_uncertainty_model`) or an already built
    :class:`FactoryModel`.  Any other model type is refused: study entry points build their
    evaluation world through the factory (review R3), never by instantiating a sampling class
    directly.  Returns ``(model, {"opt": ..., "validation": ..., "test": ...})`` (only the requested
    streams)."""
    if isinstance(spec_or_model, UncertaintySpec):
        model = build_uncertainty_model(spec_or_model, model_id=model_id)
    elif isinstance(spec_or_model, FactoryModel):
        model = spec_or_model
    else:
        raise TypeError("build_world needs an UncertaintySpec or a FactoryModel (uncertainty factory); got "
                        f"{type(spec_or_model).__name__}")
    return model, model.draw_world(streams, n_opt=n_opt, n_validation=n_validation, n_test=n_test)


def stream_name(stream_id: str) -> str:
    """Purpose name of a stream id such as ``root=1103/test`` or ``root=1103/outer/17``."""
    parts = str(stream_id).split("/")
    return parts[1] if len(parts) > 1 else ""


def run_methods(problem: RationProblem, specs: Sequence[MethodSpec], *, opt_draws: DrawSet,
                validation_draws: Optional[DrawSet] = None,
                solver_options: Optional[SolverOptions] = None) -> list[MethodRun]:
    """Solve every spec on the same problem and ``opt`` draws; select parameters on ``validation``."""
    require_stream(opt_draws, ("opt",), "smoke_pipeline.run_methods(opt_draws)")
    if validation_draws is not None:
        require_stream(validation_draws, ("validation",), "smoke_pipeline.run_methods(validation_draws)")
        if validation_draws.model_fingerprint != opt_draws.model_fingerprint:
            raise WorldMismatchError("validation draws come from a different model than the opt draws "
                                     f"({validation_draws.model_id} vs {opt_draws.model_id}); selection and "
                                     "optimisation must use one world")
    world = opt_draws.model_fingerprint
    runs: list[MethodRun] = []
    for spec in specs:
        fn = get_method(spec.method_id)
        od = opt_draws if spec.uses_opt_draws else None
        if spec.selection is not None:
            if validation_draws is None:
                raise ValueError(f"{spec.name}: a selection needs validation draws")
            s = dict(spec.selection)
            sel = select_parameter_on_validation(
                fn, problem, validation_draws, param_name=str(s["param_name"]), grid=list(s["grid"]),
                target_alpha=float(s["target_alpha"]), screening_rule=str(s["screening_rule"]),
                confidence=s.get("confidence"), base_params=dict(spec.params), opt_draws=od,
                solver_options=solver_options, consumer=f"smoke_pipeline:{spec.name}")
            runs.append(MethodRun(spec, sel.selected_result, sel, world_fingerprint=world))
        else:
            res = fn(problem, opt_draws=od, params=dict(spec.params), solver_options=solver_options)
            runs.append(MethodRun(spec, res, world_fingerprint=world))
    return runs


def evaluate_on_test(runs: Sequence[MethodRun], problem: RationProblem, test_draws: DrawSet, *,
                     world_shift_scenario: Optional[str] = None) -> list[MethodRun]:
    """Score every ration with the public evaluator on the shared ``test`` DrawSet (in place).

    The test draws must come from the model whose ``opt`` draws the methods received
    (``MethodRun.world_fingerprint``); otherwise :class:`WorldMismatchError`, unless the caller names
    the deliberate change of world in ``world_shift_scenario`` (recorded on every run)."""
    require_stream(test_draws, ("test",), "smoke_pipeline.evaluate_on_test")
    shift = None if world_shift_scenario is None else str(world_shift_scenario).strip()
    if world_shift_scenario is not None and not shift:
        raise ValueError("world_shift_scenario must be a non-empty scenario id")
    for r in runs:
        if r.world_fingerprint is not None and r.world_fingerprint != test_draws.model_fingerprint:
            if shift is None:
                raise WorldMismatchError(f"{r.spec.name}: test draws ({test_draws.model_id}) come from a different "
                                         "model than the optimisation draws; name the scenario in "
                                         "world_shift_scenario if this is intended")
            r.world_shift_scenario = shift
    for r in runs:
        used: list[str] = []
        if r.result is not None:
            used.extend(r.result.streams_used)
        if r.selection is not None:
            used.append(r.selection.validation_stream_id)
            for c in r.selection.candidates:
                used.extend(c.solve_result.streams_used)
        leaked = sorted({u for u in used if stream_name(u) == "test"})
        if leaked:
            raise LeakageError(f"{r.spec.name}: the test stream was used before evaluation: {leaked}")
        if r.has_ration:
            r.evaluation = evaluate_drawset(r.result.decision, test_draws, problem.compiled, prices=problem.prices)
    return list(runs)


