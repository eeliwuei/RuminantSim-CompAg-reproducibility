"""Shared orchestration for E0 smoke runs and the synthetic end-to-end integration test.

Status (contract 01 section 2.3): ``implemented``; exercised by
``tests/integration/test_end_to_end_synthetic.py`` (synthetic data only) and by
``experiments/E0_verification/run_smoke_nasem_dryrun.py`` (smoke).  It is **not** a pilot or official
pipeline and produces no research result.

What it enforces (contract 01 sections 8-9, 02 T1/T3/T5/T8.4/T9)
-----------------------------------------------------------------
* every method receives the same :class:`RationProblem` and the same ``opt`` draws;
* a parameter is selected only on ``validation`` draws, through
  :func:`ration_reliability.optimization.safety_margin.select_parameter_on_validation`
  (lowest-cost grid value meeting the declared screen; ``not_met`` is kept, never tuned further);
* every returned ration ``q`` (kg as-fed/head/d) is scored by the single public evaluator
  :func:`ration_reliability.evaluation.evaluate_drawset` on **one** ``test`` DrawSet shared by all
  methods (common random numbers).  The test stream is checked with ``require_stream`` and must not
  appear in any method's ``streams_used``;
* a method without a ration (infeasible, time limit without incumbent, invalid input, selection
  ``not_met``) stays in every table as a row whose cost and risk fields are empty (``None``),
  never 0 (contract section 8 "禁止把无解返回空配方后记成本为零"; acceptance D10);
* one evaluation world (review R3): the ``opt``, ``validation`` and ``test`` draws are generated by
  one model built by the uncertainty factory (:func:`build_world`); :func:`run_methods` refuses
  validation draws of another model and :func:`evaluate_on_test` refuses test draws of another
  model (:class:`WorldMismatchError`) unless a named ``world_shift_scenario`` is declared.  A nominal
  method only ignores the uncertainty while optimising; it is scored in the same world.

Nothing here scores a ration by itself, relaxes a constraint or re-normalises the realised DM.
"""

